    // Method untuk mengaktifkan Mode Edit dan mengisi komponen dengan data lama
    public void setEditMode(String idRiwayat, String kodeKambing, String tanggal, String keterangan, String berat) {
        this.idRiwayatToEdit = idRiwayat;
        
        // 1. Otomatis pilih JComboBox berdasarkan KODE Kambing
        for (int i = 0; i < PilihKambing.getItemCount(); i++) {
            // Tambahkan .toString() untuk jaga-jaga kalau tipe comboboxnya Object
            String item = PilihKambing.getItemAt(i).toString(); 
            
            // Kita cek APAKAH AKHIRAN DARI ITEM SAMA DENGAN KODE KAMBING
            if (item != null && item.endsWith(" - " + kodeKambing)) { 
                PilihKambing.setSelectedIndex(i);
                break;
            }
        }
        
        // 2. Set Tanggal lama ke JCalendarComboBox
        try {
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
            java.util.Date date = sdf.parse(tanggal);
            TglPeriksa.setDate(date);
        } catch (Exception e) {
            // Jika format tanggal bermasalah, biarkan default tanggal hari ini
        }
        
        // 3. Set text field Berat dan JTextPane Keterangan
        BeratTerkini.setText(berat);
        KeteranganKmbing.setText(keterangan);
        
        // 4. Ganti teks tombol Simpan menjadi Perbarui biar estetis
        btnSimpan.setText("Perbarui Data");
    }
    
    // Method baru untuk narik data dari database (SUDAH DI-FILTER STATUSNYA)
    private void loadDataKambing() {
        PilihKambing.removeAllItems(); // Bersihkan item bawaan
        PilihKambing.addItem("- Pilih Kambing -"); // Opsi default paling atas

        try {
            java.sql.Connection conn = sistemmanajemenpenjualanhewanternak.Utils.Database.getKoneksi();
            java.sql.Statement stmt = conn.createStatement();
            
            // --- INI QUERY YANG BARU ---
            // Kita pakai WHERE status IN (...) untuk mengambil multi-kondisi
            String sql = "SELECT id_kambing, kode_kambing FROM kambing WHERE status IN ('Tersedia', 'Sakit')";
            
            java.sql.ResultSet rs = stmt.executeQuery(sql);

            // Looping data dari database ke dalam Combobox
            while (rs.next()) {
                String id = rs.getString("id_kambing");
                String kode = rs.getString("kode_kambing");
                
                // Masukkan ke combobox dengan format "ID - Kode" (Contoh: "6 - 001")
                PilihKambing.addItem(id + " - " + kode);
            }
            
            rs.close();
            stmt.close();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat data kambing: " + e.getMessage());
        }
    }


