    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        try {
            String kambingTerpilih = PilihKambing.getSelectedItem().toString();
            if (kambingTerpilih.equals("- Pilih Kambing -")) {
                JOptionPane.showMessageDialog(this, "Harap pilih kambing terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String idKambing = kambingTerpilih.split(" - ")[0]; 
            String berat = BeratTerkini.getText();
            String keterangan = KeteranganKmbing.getText();

            java.util.Date tgl = TglPeriksa.getDate();
            if (tgl == null) {
                JOptionPane.showMessageDialog(this, "Harap isi tanggal pemeriksaan!", "Peringatan", JOptionPane.WARNING_MESSAGE);
                return;
            }
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
            String tanggalPeriksa = sdf.format(tgl);

            if(berat.isEmpty() || keterangan.isEmpty()){
                JOptionPane.showMessageDialog(this, "Harap isi semua data!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            java.sql.Connection conn = Database.getKoneksi();
            java.sql.PreparedStatement pst;

            // --- LOGIC PERCABANGAN TAMBAH VS EDIT DI SINI ---
            if (idRiwayatToEdit == null) {
                // Jika null, jalankan query TAMBAH DATA (INSERT)
                String sql = "INSERT INTO riwayat_kesehatan (id_kambing, tanggal_pemeriksaan, keterangan, berat_saat_ini) VALUES (?, ?, ?, ?)";
                pst = conn.prepareStatement(sql);
                pst.setString(1, idKambing);
                pst.setString(2, tanggalPeriksa);
                pst.setString(3, keterangan);
                pst.setString(4, berat);
            } else {
                // Jika ada isinya, jalankan query PERBARUI DATA (UPDATE) sesuai ID-nya
                String sql = "UPDATE riwayat_kesehatan SET id_kambing = ?, tanggal_pemeriksaan = ?, keterangan = ?, berat_saat_ini = ? WHERE id_riwayat = ?";
                pst = conn.prepareStatement(sql);
                pst.setString(1, idKambing);
                pst.setString(2, tanggalPeriksa);
                pst.setString(3, keterangan);
                pst.setString(4, berat);
                pst.setString(5, idRiwayatToEdit); // Parameter WHERE
            }

            pst.executeUpdate();
            pst.close();

            if (formUtama != null) {
                formUtama.loadDataTabel(); // Refresh isi JTable utama
                JOptionPane.showMessageDialog(this, "Data berhasil disimpan!");
                this.dispose(); // Tutup pop-up form input
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

