    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        if (idSupplier == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data dulu!");
            return;
        }

        int jawab = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Yakin ingin menghapus?",
            "Konfirmasi",
            javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (jawab == javax.swing.JOptionPane.YES_OPTION) {
            try {
               Connection conn = Database.getKoneksi();

                String sql = "DELETE FROM supplier_kambing WHERE id_supplier=?";
                java.sql.PreparedStatement ps = conn.prepareStatement(sql);
                ps.setInt(1, idSupplier);

                ps.executeUpdate();

                javax.swing.JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
                tampilData();
                resetForm();

            } catch (Exception e) {
               javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
            }
        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        try {
            Connection conn = Database.getKoneksi();

            String sql = "INSERT INTO supplier_kambing (nama_supplier, kontak, alamat) VALUES (?,?,?)";
            java.sql.PreparedStatement ps = conn.prepareStatement(sql);

            ps.setString(1, txtNama.getText());
            ps.setString(2, txtKontak.getText());
            ps.setString(3, txtAlamat.getText());
            ps.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "Data berhasil disimpan!");
            tampilData();
            resetForm();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void tableSupplierMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableSupplierMouseClicked
        // TODO add your handling code here:
        int baris = tableSupplier.getSelectedRow();

        idSupplier = Integer.parseInt(tableSupplier.getValueAt(baris, 0).toString());

        txtNama.setText(tableSupplier.getValueAt(baris, 1).toString());
        txtKontak.setText(tableSupplier.getValueAt(baris, 2).toString());
        txtAlamat.setText(tableSupplier.getValueAt(baris, 3).toString());
        
        tampilDetail(idSupplier);
    }//GEN-LAST:event_tableSupplierMouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (idSupplier == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data dulu!");
            return;
        }

        try {
            Connection conn = Database.getKoneksi();

            String sql = "UPDATE supplier_kambing SET nama_supplier=?, kontak=?, alamat=? WHERE id_supplier=?";
            java.sql.PreparedStatement ps = conn.prepareStatement(sql);

            ps.setString(1, txtNama.getText());
            ps.setString(2, txtKontak.getText());
            ps.setString(3, txtAlamat.getText());
            ps.setInt(4, idSupplier);

            ps.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "Data berhasil diupdate!");
            tampilData();
            resetForm();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

