    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Nama");
        model.addColumn("Kontak");
        model.addColumn("Alamat");

        try {
            Connection conn = Database.getKoneksi();
            String sql = "SELECT * FROM supplier_kambing";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("id_supplier"),
                    rs.getString("nama_supplier"),
                    rs.getString("kontak"),
                    rs.getString("alamat")
                });
            }

        tableSupplier.setModel(model);

    } catch (Exception e) {
        System.out.println(e.getMessage());
    }
}
    
    private void resetForm() {
        txtNama.setText("");
        txtKontak.setText("");
        txtAlamat.setText("");
        idSupplier = 0;
    }
    
    private void tampilDetail(int id) {
        try {
            Connection conn = Database.getKoneksi();

            String sql = "SELECT * FROM supplier_kambing WHERE id_supplier=?";
            java.sql.PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, id);

            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                lblNama.setText(rs.getString("nama_supplier"));
                lblKontak.setText(rs.getString("kontak"));
                lblAlamat.setText(rs.getString("alamat"));
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
