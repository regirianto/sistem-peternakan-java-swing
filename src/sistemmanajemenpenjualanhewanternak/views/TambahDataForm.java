    // Method logika untuk menyimpan ke database
    private void simpanData() {
        String nama = txtNama.getText();
        String nim = txtNim.getText();

        // Validasi agar data tidak kosong
        if (nama.isEmpty() || nim.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama dan NIM tidak boleh kosong!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // 1. Panggil koneksi dari class Database yang sudah kita buat sebelumnya
            Connection conn = Database.getKoneksi();
            
            // 2. Siapkan query SQL
            String sql = "INSERT INTO mahasiswa (nama, nim) VALUES (?, ?)";
            PreparedStatement stmt = conn.prepareStatement(sql);
            
            // 3. Masukkan data dari form ke dalam query (?)
            stmt.setString(1, nama);
            stmt.setString(2, nim);
            
            // 4. Eksekusi query ke database
            stmt.executeUpdate();
            
            // 5. Beri notifikasi sukses dan kosongkan form
            JOptionPane.showMessageDialog(this, "Data berhasil disimpan ke Database!");
            txtNama.setText("");
            txtNim.setText("");
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data: " + e.getMessage(), "Error Database", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
             JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    

